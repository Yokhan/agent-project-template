"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const storage = require("./lib/storage-operation-registry.js");
const adapter = require("./lib/storage-operation-hooks.js");
const policy = require("./lib/codex-turn-policy.js");
const hooks = require("./codex-hooks.js");

async function main() {
  const base = process.env.AGENT_RUN_COPY_DIR;
  assert(base, "Run through managed-temp");
  const root = path.join(base, "storage-hook-fixture");
  fs.mkdirSync(root, { recursive: true });
  const input = { session_id: "writer", turn_id: "turn", prompt: "Спасибо" };
  const record = policy.startRequest(root, input, { workflowDepth: "direct", delegationDecision: { required: false } });
  const startup = await hooks.handle({ ...input, hook_event_name: "SessionStart" }, root);
  assert.match(startup.hookSpecificOutput.additionalContext, /Shared storage coordination/u);
  assert.equal(fs.existsSync(storage.registryPath(root)), false, "startup context must not create a database");
  assert.equal(adapter.isKnownBulkCopy(root, "robocopy source target /L"), false);
  assert.equal(adapter.isKnownBulkCopy(root, "robocopy source preview /L && robocopy source actual /E"), true);
  assert.equal(adapter.isKnownBulkCopy(root, "node scripts/managed-temp.js run -- node -e 'fs.cpSync(a,b)'"), false);
  assert.equal(adapter.isKnownBulkCopy(root, "echo node scripts/managed-temp.js run -- node; robocopy a b"), true);
  assert.equal(adapter.isKnownBulkCopy(root, "Get-ChildItem -Recurse"), false);
  assert.equal(adapter.isKnownBulkCopy(root, "Get-ChildItem; robocopy source target /E"), true);
  assert.equal(adapter.isKnownBulkCopy(root, "copy-item source target -Recurse"), true);
  const source = path.join(root, "source.bin");
  fs.writeFileSync(source, "source");
  const target = path.join(root, "output");
  const writer = storage.claim(root, { source, target, digest: crypto.createHash("sha256").update("source").digest("hex"), purpose: "test", reserveBytes: 32, session: input.session_id, request: record.state.requestId }, { availableBytes: Number.MAX_SAFE_INTEGER });
  const copy = { ...input, hook_event_name: "PreToolUse", tool_name: "exec_command", tool_input: { cmd: `robocopy "${source}" "${target}" /E` } };
  assert.doesNotThrow(() => adapter.beforeTool(root, copy, record));
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `robocopy "${source}" "${target}-other" /E` } }, record), /exact target/u);
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `robocopy "${target}" "${target}-other" /E` } }, record), /exact target/u);
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `robocopy source "${target}-other" /E; Write-Output "${target}"` } }, record), /chained shell/u);
  assert.doesNotThrow(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `copy-item "${source}" -Destination "${target}" -Recurse` } }, record));
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `cp -r -t "${target}-other" "${target}"` } }, record), /exact target/u);
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `cp -r --target-directory "${target}-other" "${target}"` } }, record), /exact target/u);
  assert.throws(() => adapter.beforeTool(root, { ...copy, tool_input: { cmd: `robocopy "${source}" "${target}" /JOB:unknown` } }, record), /exact target/u);
  const foreign = { state: { requestId: "neighbor-request" } };
  assert.throws(() => adapter.beforeTool(root, { ...copy, session_id: "neighbor" }, foreign), /different chat/u);
  assert.equal(adapter.unfinished(root, { session_id: "neighbor" }, foreign), null);
  assert.match(adapter.unfinished(root, input, record), /not settled/u);
  const protectedPath = path.join(root, "old-baseline");
  fs.mkdirSync(protectedPath);
  storage.protect(root, { path: protectedPath, reason: "Referenced by current release", session: "owner", request: "review" });
  const visible = adapter.context(root, input, record);
  assert(visible.includes("old-baseline"));
  assert(!visible.includes(writer.token), "hook context must not expose writer credentials");
  const accepted = await hooks.handle(copy, root);
  assert.deepEqual(accepted, {});
  const blocked = await hooks.handle({ ...input, hook_event_name: "Stop", last_assistant_message: "Пожалуйста." }, root);
  assert.match(blocked.reason || blocked.stopReason || "", /storage-operation-unfinished/u);
  const neighborInput = { session_id: "neighbor", turn_id: "neighbor-turn", prompt: "Спасибо" };
  policy.startRequest(root, neighborInput, { workflowDepth: "direct", delegationDecision: { required: false } });
  const neighborStop = await hooks.handle({ ...neighborInput, hook_event_name: "Stop", last_assistant_message: "Пожалуйста." }, root);
  assert(!JSON.stringify(neighborStop).includes("storage-operation-unfinished"), "neighbor's live writer must not block Stop");
  storage.abandon(root, { ...writer, session: input.session_id, request: record.state.requestId });
  assert.equal(adapter.unfinished(root, input, record), null);
  console.log("Storage hook ownership, target binding and native lifecycle checks passed");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
